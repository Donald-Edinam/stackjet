import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packsDir = join(root, "packages", "sdk-packs");
const checkOnly = process.argv.includes("--check");

// Resolve which packs to process: --pack sdk-57 targets one, default targets all.
const packFlagIndex = process.argv.indexOf("--pack");
const requestedPack = packFlagIndex !== -1 ? process.argv[packFlagIndex + 1] : undefined;

function discoverPacks() {
  return readdirSync(packsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name.startsWith("sdk-"))
    .map((entry) => entry.name)
    .sort();
}

function collectFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`SDK packs cannot contain symlinks: ${absolute}`);
    return entry.isDirectory() ? collectFiles(absolute) : [absolute];
  });
}

function syncPack(packName) {
  const packRoot = join(packsDir, packName);
  const templateRoot = join(packRoot, "template");
  const generatedPath = join(packRoot, "src", "template.generated.ts");
  const manifestPath = join(packRoot, "pack.json");

  if (!existsSync(templateRoot)) {
    throw new Error(`Template directory not found for ${packName}: ${templateRoot}`);
  }

  // Extract SDK version number from pack name (e.g., "sdk-57" -> "57")
  const sdkVersion = packName.replace("sdk-", "");

  const files = Object.fromEntries(
    collectFiles(templateRoot)
      .map((path) => [relative(templateRoot, path).replaceAll("\\", "/"), readFileSync(path, "utf8")])
      .sort(([left], [right]) => left.localeCompare(right)),
  );
  const hash = createHash("sha256");
  for (const [path, content] of Object.entries(files)) {
    hash.update(path);
    hash.update("\0");
    hash.update(content);
    hash.update("\0");
  }
  const checksum = hash.digest("hex");
  const generated = `// Generated by scripts/sync-sdk-pack.mjs. Do not edit.\nexport const sdk${sdkVersion}FilesSha256 = ${JSON.stringify(checksum)};\nexport const sdk${sdkVersion}Files: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(files, null, 2)});\n`;
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  manifest.filesSha256 = checksum;
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;

  if (checkOnly) {
    if (!existsSync(generatedPath) || readFileSync(generatedPath, "utf8") !== generated) {
      throw new Error(`SDK ${sdkVersion} generated template is stale. Run pnpm sdk:sync.`);
    }
    if (readFileSync(manifestPath, "utf8") !== manifestText) {
      throw new Error(`SDK ${sdkVersion} manifest checksum is stale. Run pnpm sdk:sync.`);
    }
    console.log(`SDK ${sdkVersion} checksum verified: ${checksum}`);
  } else {
    writeFileSync(generatedPath, generated, "utf8");
    writeFileSync(manifestPath, manifestText, "utf8");
    console.log(`SDK ${sdkVersion} pack synchronized: ${checksum}`);
  }
}

const packs = requestedPack ? [requestedPack] : discoverPacks();
for (const pack of packs) {
  syncPack(pack);
}
